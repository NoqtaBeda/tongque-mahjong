"""策略头（P0）：每个候选打牌一个价值。

和 `train.py` 的区别：
- 同一个主干后面挂两个头：价值头（1 维，和现在一样）+ 策略头（34 维，每张牌的 logit）
- 额外读 `*.act.bin` 侧车（每条样本这一步实际打了哪张牌）
- 策略部分用 REINFORCE：`loss = -log_softmax(logits)[chosen] * advantage`，
  advantage 取「本局净得分 − 价值头的预测」并做标准化、截断，避免方差炸掉

用法：
    python tools/torch/train-policy.py --data=.data/samples-align.bin \
        --init=packages/core/src/ai/nn/weights.ts \
        --out=.data/model-policy.ts --out-policy=.data/policy.ts
"""

import argparse
import os
import struct
import sys
import time

import numpy as np
import torch
from torch import nn

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from export_weights import write_weights_ts  # noqa: E402
from model import correlation, pick_device, split_by_group3  # noqa: E402

DEFAULT_OUT = ".data/model-policy.ts"
DEFAULT_POLICY_OUT = ".data/policy.ts"
TILES = 34


def load_with_actions(files):
    """读主文件 + .act.bin 侧车；返回 features/targets/groups/actions/dim"""
    all_features = []
    all_targets = []
    all_groups = []
    all_actions = []
    total = 0
    dim = 0
    group_offset = 0
    for path in files:
        with open(path, "rb") as handle:
            raw = handle.read()
        count, dim = struct.unpack_from("<II", raw, 0)
        offset = 8
        groups = np.frombuffer(raw, dtype="<u4", count=count, offset=offset).astype(
            np.int64
        )
        offset += count * 4
        body = np.frombuffer(
            raw, dtype="<f4", count=count * (dim + 1), offset=offset
        ).astype(np.float32)
        body = body.reshape(count, dim + 1)
        action_path = path.replace(".bin", ".act.bin")
        if not os.path.exists(action_path):
            raise SystemExit(f"✖ 缺少动作侧车：{action_path}（用新版 gen.ts 重新生成）")
        actions = np.frombuffer(open(action_path, "rb").read(), dtype=np.uint8)
        if actions.size != count:
            raise SystemExit(f"✖ 侧车条数不符：{action_path}")
        all_features.append(body[:, :dim])
        all_targets.append(body[:, dim])
        all_groups.append(groups + group_offset)
        all_actions.append(actions)
        group_offset += int(groups.max()) + 1 if count else 0
        total += count
    return (
        np.concatenate(all_features),
        np.concatenate(all_targets),
        np.concatenate(all_groups),
        np.concatenate(all_actions),
        dim,
    )


class TwoHead(nn.Module):
    def __init__(self, dim, h1, h2):
        super().__init__()
        self.trunk = nn.Sequential(nn.Linear(dim, h1), nn.ReLU(), nn.Linear(h1, h2), nn.ReLU())
        self.value = nn.Linear(h2, 1)
        self.policy = nn.Linear(h2, TILES)

    def forward(self, x):
        hidden = self.trunk(x)
        return self.value(hidden).squeeze(-1), self.policy(hidden)


def write_policy_ts(model, path, note):
    """策略头导出成 TS：base64 float32，结构和 nn/policy.ts 的加载器对应"""
    import base64

    def blob(tensor):
        array = tensor.detach().cpu().numpy().astype("<f4")
        return base64.b64encode(array.tobytes()).decode("ascii")

    lines = [
        "// AUTO-GENERATED by tools/torch/train-policy.py —— 不要手改。",
        f"// {note}",
        "import type { PolicyWeights } from './policy.ts';",
        "",
        "export const POLICY_WEIGHTS: PolicyWeights = {",
        f"  dim0: {model.trunk[0].in_features},",
        f"  dim1: {model.trunk[0].out_features},",
        f"  dim2: {model.trunk[2].out_features},",
        f"  tiles: {TILES},",
        f"  w1: '{blob(model.trunk[0].weight)}',",
        f"  b1: '{blob(model.trunk[0].bias)}',",
        f"  w2: '{blob(model.trunk[2].weight)}',",
        f"  b2: '{blob(model.trunk[2].bias)}',",
        f"  w3: '{blob(model.policy.weight)}',",
        f"  b3: '{blob(model.policy.bias)}',",
        "};",
        "",
    ]
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def export_value_model(two_head, dim, h1, h2):
    """把双头网络里的「主干 + 价值头」拷成一个标准 Mlp，交给 write_weights_ts"""
    from model import Mlp

    plain = Mlp(dim, h1, h2)
    plain.fc1.weight.data.copy_(two_head.trunk[0].weight.data)
    plain.fc1.bias.data.copy_(two_head.trunk[0].bias.data)
    plain.fc2.weight.data.copy_(two_head.trunk[2].weight.data)
    plain.fc2.bias.data.copy_(two_head.trunk[2].bias.data)
    plain.fc3.weight.data.copy_(two_head.value.weight.data)
    plain.fc3.bias.data.copy_(two_head.value.bias.data)
    return plain


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, help="逗号分隔的 .bin（需要同名 .act.bin）")
    ap.add_argument("--epochs", type=int, default=25)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--hidden1", type=int, default=128)
    ap.add_argument("--hidden2", type=int, default=64)
    ap.add_argument("--policy-weight", type=float, default=1.0)
    ap.add_argument("--clip", type=float, default=2.0, help="advantage 截断倍数")
    ap.add_argument("--valid-ratio", type=float, default=0.15)
    ap.add_argument("--test-ratio", type=float, default=0.15)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--init", default="", help="价值主干从现有 weights.ts 热启动")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--out-policy", default=DEFAULT_POLICY_OUT)
    args = ap.parse_args()

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    device = pick_device()

    files = [path.strip() for path in args.data.split(",") if path.strip()]
    features, targets, groups, actions, dim = load_with_actions(files)
    train_idx, val_idx, test_idx = split_by_group3(
        groups, args.valid_ratio, args.test_ratio, args.seed
    )

    is_discard = (actions & 0x80) != 0
    chosen = (actions & 0x3F).astype(np.int64)
    print(
        f"样本 {len(targets)} · 维度 {dim} · 打牌样本 {int(is_discard.sum())}"
        f"（{is_discard.mean() * 100:.0f}%）· 标签均值 {targets.mean() * 12:.3f} 分"
    )

    x = torch.from_numpy(features).to(device)
    y = torch.from_numpy(targets).to(device)
    act = torch.from_numpy(chosen).to(device)
    mask = torch.from_numpy(is_discard).to(device)
    tr = torch.from_numpy(train_idx).to(device)
    va = torch.from_numpy(val_idx).to(device)
    te = torch.from_numpy(test_idx).to(device)

    model = TwoHead(dim, args.hidden1, args.hidden2).to(device)
    if args.init:
        from export_weights import read_weights_ts

        loaded = read_weights_ts(args.init)
        got = (loaded["dim0"], loaded["dim1"], loaded["dim2"])
        want = (dim, args.hidden1, args.hidden2)
        if got != want:
            raise SystemExit(f"✖ 结构不符：{args.init} 是 {got}，当前配置是 {want}")
        state = loaded["state"]
        # train.py 的三层是 (W1,b1,W2,b2,W3,b3)，这里的主干只有两层 + 两个头
        with torch.no_grad():
            model.trunk[0].weight.copy_(state["fc1.weight"])
            model.trunk[0].bias.copy_(state["fc1.bias"])
            model.trunk[2].weight.copy_(state["fc2.weight"])
            model.trunk[2].bias.copy_(state["fc2.bias"])
            model.value.weight.copy_(state["fc3.weight"])
            model.value.bias.copy_(state["fc3.bias"])
        print(f"已从 {args.init} 热启动（主干 + 价值头）")

    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
    value_loss_fn = nn.MSELoss()

    best_score, best_epoch = -2.0, 0
    best_state = {k: v.detach().clone() for k, v in model.state_dict().items()}
    started = time.time()

    for epoch in range(1, args.epochs + 1):
        model.train()
        perm = tr[torch.randperm(tr.numel(), device=device)]
        for start in range(0, perm.numel(), args.batch):
            idx = perm[start : start + args.batch]
            values, logits = model(x[idx])
            loss_value = value_loss_fn(values, y[idx])
            # advantage：用本局实际净得分当回报，价值预测当基线
            advantage = (y[idx] - values.detach()).detach()
            scale = advantage.std().clamp_min(1e-6)
            advantage = (advantage / scale).clamp(-args.clip, args.clip)
            log_probs = torch.log_softmax(logits, dim=1)
            picked = log_probs.gather(1, act[idx].unsqueeze(1)).squeeze(1)
            # 只有打牌决策才训策略头；鸣牌/过样本不参与
            weight = mask[idx].float()
            loss_policy = (
                -(picked * advantage * weight).sum() / weight.sum().clamp_min(1.0)
            )
            loss = loss_value + args.policy_weight * loss_policy
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

        model.eval()
        with torch.no_grad():
            val_values, val_logits = model(x[va])
            val_r = correlation(val_values, y[va])
            mask_va = mask[va]
            if mask_va.sum() > 0:
                log_probs = torch.log_softmax(val_logits[mask_va], dim=1)
                picked = log_probs.gather(1, act[va][mask_va].unsqueeze(1))
                policy_nll = float(-picked.mean())
                # 策略头的「命中率」：argmax 是否等于实际打法
                acc = float((val_logits[mask_va].argmax(dim=1) == act[va][mask_va]).float().mean())
            else:
                policy_nll, acc = 0.0, 0.0
        # 综合分：价值相关 + 策略命中率（早停用）
        score = val_r + acc
        if score > best_score:
            best_score, best_epoch = score, epoch
            best_state = {k: v.detach().clone() for k, v in model.state_dict().items()}
        print(
            f"epoch {epoch:2d} · val r {val_r:.3f} · 策略 nll {policy_nll:.3f}"
            f" · 命中率 {acc * 100:.1f}% · {time.time() - started:.0f}s"
        )

    model.load_state_dict(best_state)
    model.eval()
    with torch.no_grad():
        test_values, test_logits = model(x[te])
        test_r = correlation(test_values, y[te])
        mask_te = mask[te]
        acc = float((test_logits[mask_te].argmax(dim=1) == act[te][mask_te]).float().mean())
    print(f"\n测试集：价值 r={test_r:.3f} · 策略命中率 {acc * 100:.1f}%（第 {best_epoch} 轮）")

    note_value = f"{len(targets)} 个样本（对齐后）· 测试集 r={test_r:.3f} · {dim}→{args.hidden1}→{args.hidden2}→1"
    write_weights_ts(
        export_value_model(model, dim, args.hidden1, args.hidden2).to(device),
        args.out,
        note_value,
    )
    write_policy_ts(
        model,
        args.out_policy,
        f"策略头 {dim}→{args.hidden1}→{args.hidden2}→{TILES} · 命中率 {acc * 100:.1f}%",
    )
    print(f"价值权重：{args.out}")
    print(f"策略权重：{args.out_policy}")
    print(f"总耗时 {time.time() - started:.1f}s")


if __name__ == "__main__":
    main()
