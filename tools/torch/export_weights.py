"""把 PyTorch 的 state_dict 导出成 `packages/core/src/ai/nn/weights.ts`。

只写三段维度 + **一个 base64 字符串**（float32 小端字节流，顺序 w1 → b1 → w2 → b2 → w3 → b3），
由 `packages/core/src/ai/nn/model.ts` 在模块加载时解码。

为什么不用数字数组：23809 个数字字面量在模块解析时约 51ms，base64 解码不到 2ms。

TS 侧 `MlpWeights` 的布局：
    w1  dim1 × dim0（行主序，行 = 输出神经元，列 = 输入）
    w2  dim2 × dim1
    w3  1 × dim2
PyTorch 的 `nn.Linear.weight` 也是 (out, in)，所以**直接按行展平即可，不需要转置**。
"""

import base64

import torch

HEADER = """// AUTO-GENERATED by tools/torch/export_weights.py —— 不要手改。
// {note}
export const NN_DIM0 = {dim0};
export const NN_DIM1 = {dim1};
export const NN_DIM2 = {dim2};

// float32 小端字节流（布局 w1 → b1 → w2 → b2 → w3 → b3），解码见同目录 model.ts
export const NN_WEIGHTS_B64 =
  '{b64}';
"""


def _payload(model):
    """按固定顺序拼成 float32 小端字节流，再 base64。"""
    parts = [
        model.fc1.weight,
        model.fc1.bias,
        model.fc2.weight,
        model.fc2.bias,
        model.fc3.weight,
        model.fc3.bias,
    ]
    blob = b"".join(
        tensor.detach().to("cpu", torch.float32).numpy().astype("<f4").tobytes()
        for tensor in parts
    )
    return base64.b64encode(blob).decode("ascii")


def to_weights_ts(model, note):
    """把模型转成 weights.ts 的文本内容。"""
    return HEADER.format(
        note=note,
        dim0=model.fc1.in_features,
        dim1=model.fc1.out_features,
        dim2=model.fc2.out_features,
        b64=_payload(model),
    )


def write_weights_ts(model, path, note):
    text = to_weights_ts(model, note)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return path


def read_weights_ts(path):
    """把 weights.ts（base64 的 float32 字节流）读回成 PyTorch state_dict。

    用于「迁移学习」：在已有的线上权重基础上继续训练，而不是从零开始。
    """
    import base64
    import re

    import numpy as np
    import torch

    text = open(path, encoding="utf-8").read()
    dim0 = int(re.search(r"NN_DIM0 = (\d+)", text).group(1))
    dim1 = int(re.search(r"NN_DIM1 = (\d+)", text).group(1))
    dim2 = int(re.search(r"NN_DIM2 = (\d+)", text).group(1))
    match = re.search(r"NN_WEIGHTS_B64 =\s*'([^']+)'", text)
    if match is None:
        raise SystemExit(f"✖ {path} 里找不到 NN_WEIGHTS_B64")

    flat = np.frombuffer(base64.b64decode(match.group(1)), dtype="<f4")
    names = ["fc1.weight", "fc1.bias", "fc2.weight", "fc2.bias", "fc3.weight", "fc3.bias"]
    shapes = [(dim1, dim0), (dim1,), (dim2, dim1), (dim2,), (1, dim2), (1,)]
    state = {}
    cursor = 0
    for name, shape in zip(names, shapes):
        size = int(np.prod(shape))
        chunk = flat[cursor : cursor + size].reshape(shape)
        state[name] = torch.from_numpy(chunk.copy())
        cursor += size
    return {"dim0": dim0, "dim1": dim1, "dim2": dim2, "state": state}
